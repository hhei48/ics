print("Welcome to the computer hardware store!")
usb=int(input("How many USB storage device would you like to buy? "))
keyboard=int(input("How many keyboard would you like to buy? "))
mouse=int(input("How many mouse would you like to buy? "))
subtotal=19.99*float(usb)+49.99*float(keyboard)+25.99*float(mouse)
subtotal=round(subtotal, 2)
tax=round(0.13*subtotal, 2)
grand_total=round(subtotal+tax, 2)
